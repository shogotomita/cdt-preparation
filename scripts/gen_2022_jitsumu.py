def q(
    display: str,
    stem: str,
    choices: list,
    overall: str,
    correct: list[str],
    images: list[str] | None = None,
    id_suffix: str | None = None,
) -> dict:
    global _num
    _num += 1
    sid = id_suffix or display.replace("(", "-").replace(")", "").replace("①", "-1").replace("②", "-2").replace("③", "-3")
    item: dict = {
        "id": f"{YEAR}-{SUBJECT}-{sid}",
        "number": _num,
        "displayNumber": display,
        "year": YEAR,
        "subject": SUBJECT,
        "stem": stem,
        "choices": [],
        "overallExplanation": overall,
        "correctKeys": correct,
    }
    if images:
        item["images"] = images
    for c in choices:
        ch = {"key": c[0], "text": c[1], "explanation": c[2]}
        if len(c) > 3 and c[3]:
            ch["image"] = c[3]
        item["choices"].append(ch)
    return item


