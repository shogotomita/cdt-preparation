def join_jp(s: str) -> str:
    s = re.sub(r"\n+", "", s.strip())
    s = re.sub(r"[ \t]+", "", s)
    return s


def clean_choice_text(text: str) -> str:
    # Section headers glued after the last choice of the previous question
    text = re.split(
        r"(?:航空による運送に関する|次の設問について、該当する答を|日本国内における世界遺産|次の設問の行程について|次の設問の組合せについて)",
        text,
        maxsplit=1,
    )[0]
    return text.strip()


def parse_choices(body: str) -> dict[str, str]:
    # Prefer line-start choices; fall back to inline "ア．… イ．…"
    choices: dict[str, str] = {}
    for cm in re.finditer(r"(?:^|\n)([ア-エ])．(.*?)(?=(?:\n[ア-エ]．)|$)", body, re.S):
        choices[KEY[cm.group(1)]] = clean_choice_text(join_jp(cm.group(2)))
    if len(choices) == 4 and all(choices.values()):
        return choices
    choices = {}
    # Split on choice markers so names like「アシリベツ」でも壊れない
    parts = re.split(r"(?=[ア-エ]．)", join_jp(body))
    for p in parts:
        cm = re.match(r"([ア-エ])．(.+)", p)
        if not cm:
            continue
        choices[KEY[cm.group(1)]] = clean_choice_text(join_jp(cm.group(2)))
    return choices


def stem_before_choices(body: str) -> str:
    return join_jp(re.split(r"ア．", body, maxsplit=1)[0]).replace("＜図＞", "<図>")


