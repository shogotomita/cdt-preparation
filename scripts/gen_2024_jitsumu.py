def main() -> None:
    text = TMP.read_text()
    content = re.sub(r"^.*?(?=\n問\s*51\n)", "", "\n" + text, count=1, flags=re.S)
    chunks = re.split(r"\n問\s*(\d+)\n", content)
    raw: dict[int, str] = {}
    for i in range(1, len(chunks), 2):
        raw[int(chunks[i])] = chunks[i + 1]

    entries = build_entries(raw)
    assert len(entries) == 38, len(entries)

    # validate
    errors = []
    for e in entries:
        m = re.match(r"2024-jitsumu-(\d+)(?:-(\d+))?$", e["id"])
        assert m, e["id"]
        if m.group(2):
            key = (int(m.group(1)), int(m.group(2)))
        else:
            key = int(m.group(1))
        if e["correctKeys"] != ANSWERS[key]:
            errors.append(f"keys {e['id']}")
        for c in e["choices"]:
            ok = c["key"] in e["correctKeys"]
            if ok and not c["explanation"].startswith("正解。"):
                errors.append(f"exp+ {e['id']} {c['key']}")
            if not ok and not c["explanation"].startswith("不正解。"):
                errors.append(f"exp- {e['id']} {c['key']}")
        if set(x["key"] for x in e["choices"]) != {"A", "B", "C", "D"}:
            errors.append(f"choices {e['id']}")
        if not all(x["text"] for x in e["choices"]):
            errors.append(f"empty text {e['id']}")
        if not e.get("overallExplanation"):
            errors.append(f"overall {e['id']}")
    if errors:
        raise SystemExit("validation failed: " + "; ".join(errors))

    OUT.write_text(json.dumps({"questions": entries}, ensure_ascii=False, indent=2) + "\n")
    print(f"wrote {OUT} ({len(entries)} questions)")


if __name__ == "__main__":
    main()
