def build_entries(raw: dict[int, str]) -> list[dict]:
    entries: list[dict] = []

    def push(num, stem, choices, sub=None, images=None):
        if sub is None:
            qid = f"2024-jitsumu-{num}"
            disp = None
            key = num
        else:
            mark = {1: "①", 2: "②", 3: "③", 4: "④"}[sub]
            qid = f"2024-jitsumu-{num}-{sub}"
            disp = f"{num}{mark}"
            key = (num, sub)
        cex, overall = EXP[key]
        keys = ANSWERS[key]
        ch = []
        for k in ["A", "B", "C", "D"]:
            ch.append({"key": k, "text": choices[k], "explanation": cex[k]})
        e = {
            "id": qid,
            "number": num,
            "year": "2024",
            "subject": "jitsumu",
            "stem": stem,
            "choices": ch,
            "overallExplanation": overall,
            "correctKeys": keys,
        }
        if disp:
            e["displayNumber"] = disp
        if images:
            e["images"] = images
            if "<図>" not in stem:
                e["stem"] = stem + "\n\n<図>"
        entries.append(e)

    for num in sorted(raw):
        body = raw[num]
        if num in (57, 69):
            parts = re.split(r"\n([①②③④])\s*", body)
            shared = join_jp(parts[0]).replace("＜図＞", "<図>")
